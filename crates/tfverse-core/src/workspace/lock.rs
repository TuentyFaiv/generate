//! `tfverse.lock`: what was generated, from which pack version and inputs.

use schemars::JsonSchema;
use semver::Version;
use serde::{Deserialize, Serialize};

use super::{Workspace, WorkspaceError};
use crate::brand;
use crate::model::{Digest, Name, RelPath, Stack, Values};

/// The lockfile format this build reads and writes.
pub const LOCK_VERSION: u32 = 1;

const HEADER: &str = "# Generated by tfverse. Commit this file; do not edit it by hand.\n\n";

/// `tfverse.lock`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Lockfile {
	/// Format version; must be `1`.
	pub version: u32,
	/// Packs the project uses, pinned by content hash.
	#[serde(default, rename = "pack", skip_serializing_if = "Vec::is_empty")]
	pub packs: Vec<PackRecord>,
	/// Generated pieces.
	#[serde(default, rename = "instance", skip_serializing_if = "Vec::is_empty")]
	pub instances: Vec<Instance>,
}

/// A pack the project uses.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct PackRecord {
	/// Pack name.
	pub name: Name,
	/// Pack version.
	pub version: Version,
	/// Where it came from, e.g. `gh:acme/packs@v1.2.0`; absent for a folder on this machine.
	#[serde(default, skip_serializing_if = "Option::is_none")]
	pub source: Option<String>,
	/// SHA-256 of every file in the pack; a different hash for the same version is refused.
	pub digest: Digest,
	/// Id of the key that signed it; later versions must be signed by the same key.
	#[serde(default, skip_serializing_if = "Option::is_none")]
	pub signer: Option<String>,
}

/// One generated piece.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct Instance {
	/// Stable id, derived from pack, piece and inputs.
	pub id: String,
	/// Pack name.
	pub pack: Name,
	/// Pack version used.
	pub pack_version: Version,
	/// Piece name.
	pub piece: Name,
	/// Variant used, if any.
	#[serde(default, skip_serializing_if = "Option::is_none")]
	pub variant: Option<Name>,
	/// Output folder used, or `None` for the project root.
	#[serde(default, skip_serializing_if = "Option::is_none")]
	pub target: Option<RelPath>,
	/// Stack facts used, so the original can be rendered again.
	#[serde(default, skip_serializing_if = "Stack::is_empty")]
	pub stack: Stack,
	/// Resolved input values.
	#[serde(default, skip_serializing_if = "Values::is_empty")]
	pub inputs: Values,
	/// Files the piece created.
	#[serde(default, rename = "file", skip_serializing_if = "Vec::is_empty")]
	pub files: Vec<FileRecord>,
	/// Regions the piece inserted into existing files.
	#[serde(default, rename = "patch", skip_serializing_if = "Vec::is_empty")]
	pub patches: Vec<PatchRecord>,
}

/// A generated file and the hash of the version tfverse wrote.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct FileRecord {
	/// Project-relative path.
	pub path: RelPath,
	/// Hash of the original generated content.
	pub base: Digest,
}

/// A region a patch inserted, owned by its instance.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct PatchRecord {
	/// Project-relative path of the edited file.
	pub file: RelPath,
	/// Hash of the inserted text.
	pub inserted: Digest,
}

/// Why a lockfile could not be read.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum LockError {
	/// Invalid TOML or schema.
	#[error("tfverse.lock: {0}")]
	Parse(String),
	/// A format version this build does not read.
	#[error("tfverse.lock uses version {0}; this tfverse reads version {LOCK_VERSION}")]
	UnsupportedVersion(u32),
	/// Reading the lockfile failed.
	#[error(transparent)]
	Workspace(#[from] WorkspaceError),
}

impl Default for Lockfile {
	fn default() -> Self {
		Self {
			version: LOCK_VERSION,
			packs: Vec::new(),
			instances: Vec::new(),
		}
	}
}

impl Lockfile {
	/// Where the lockfile lives in a project.
	pub(crate) fn path() -> RelPath {
		RelPath::constant(brand::LOCK_FILE)
	}

	/// The project's lockfile, or an empty one.
	pub(crate) fn load(workspace: &Workspace) -> Result<Self, LockError> {
		match workspace.read(&Self::path())? {
			Some(bytes) => Self::parse(&String::from_utf8_lossy(&bytes)),
			None => Ok(Self::default()),
		}
	}

	/// Parses lockfile text.
	pub fn parse(text: &str) -> Result<Self, LockError> {
		let lock: Self = toml::from_str(text).map_err(|error| LockError::Parse(error.message().to_owned()))?;
		if lock.version != LOCK_VERSION {
			return Err(LockError::UnsupportedVersion(lock.version));
		}
		Ok(lock)
	}

	/// Serializes the lockfile with a header.
	#[must_use]
	pub fn to_toml(&self) -> String {
		let body = toml::to_string(self).unwrap_or_default();
		format!("{HEADER}{body}")
	}

	/// The instance that generated `path`, and its record.
	#[must_use]
	pub fn owner(&self, path: &RelPath) -> Option<(&Instance, &FileRecord)> {
		self.instances.iter().find_map(|instance| {
			instance
				.files
				.iter()
				.find(|file| file.path == *path)
				.map(|file| (instance, file))
		})
	}

	/// The record of the pack called `name`.
	#[must_use]
	pub fn pack(&self, name: &Name) -> Option<&PackRecord> {
		self.packs.iter().find(|pack| pack.name == *name)
	}

	/// Adds `pack`, replacing the record of the same name.
	pub fn upsert_pack(&mut self, pack: PackRecord) {
		match self.packs.iter_mut().find(|existing| existing.name == pack.name) {
			Some(existing) => *existing = pack,
			None => self.packs.push(pack),
		}
		self.packs.sort_by(|a, b| a.name.cmp(&b.name));
	}

	/// Whether the project has any instance of `piece` from `pack`.
	#[must_use]
	pub fn has_piece(&self, pack: &Name, piece: &Name) -> bool {
		self
			.instances
			.iter()
			.any(|instance| instance.pack == *pack && instance.piece == *piece)
	}

	/// Adds `instance`, replacing one with the same id.
	pub fn upsert(&mut self, instance: Instance) {
		match self.instances.iter_mut().find(|existing| existing.id == instance.id) {
			Some(existing) => *existing = instance,
			None => self.instances.push(instance),
		}
		self.instances.sort_by(|a, b| a.id.cmp(&b.id));
	}
}

/// A stable id for a piece generated with `inputs`.
#[must_use]
pub(crate) fn instance_id(pack: &Name, piece: &Name, inputs: &Values) -> String {
	let key = serde_json::to_string(&(pack, piece, inputs)).unwrap_or_default();
	format!("{piece}-{}", &Digest::of(key.as_bytes()).hex()[..10])
}

#[cfg(test)]
mod tests {
	use super::*;
	use crate::model::Value;

	fn instance(id: &str) -> Instance {
		Instance {
			id: id.to_owned(),
			pack: Name::new("default").unwrap(),
			pack_version: Version::new(1, 2, 3),
			piece: Name::new("component").unwrap(),
			variant: Some(Name::new("react").unwrap()),
			target: Some(RelPath::new("src").unwrap()),
			stack: Stack::default(),
			inputs: Values::from([("name".to_owned(), Value::String("Card".to_owned()))]),
			files: vec![FileRecord {
				path: RelPath::new("src/Card.tsx").unwrap(),
				base: Digest::of(b"x"),
			}],
			patches: vec![PatchRecord {
				file: RelPath::new("src/index.ts").unwrap(),
				inserted: Digest::of(b"y"),
			}],
		}
	}

	#[test]
	fn to_toml_should_round_trip() {
		let lock = Lockfile {
			version: LOCK_VERSION,
			packs: vec![PackRecord {
				name: Name::new("default").unwrap(),
				version: Version::new(1, 2, 3),
				source: Some("gh:acme/packs@v1.2.3".to_owned()),
				digest: Digest::of(b"pack"),
				signer: Some("F7C5EF0A9B1D2E3C".to_owned()),
			}],
			instances: vec![instance("component-1")],
		};

		assert_eq!(Lockfile::parse(&lock.to_toml()).unwrap(), lock);
	}

	#[test]
	fn parse_should_reject_future_version() {
		assert!(matches!(
			Lockfile::parse("version = 2\n"),
			Err(LockError::UnsupportedVersion(2))
		));
	}

	#[test]
	fn upsert_should_replace_same_id() {
		let mut lock = Lockfile::default();
		lock.upsert(instance("component-1"));
		lock.upsert(instance("component-1"));

		assert_eq!(lock.instances.len(), 1);
	}

	#[test]
	fn instance_id_should_change_with_inputs() {
		let (pack, piece) = (Name::new("default").unwrap(), Name::new("component").unwrap());
		let card = Values::from([("name".to_owned(), Value::String("Card".to_owned()))]);
		let list = Values::from([("name".to_owned(), Value::String("List".to_owned()))]);

		assert_ne!(instance_id(&pack, &piece, &card), instance_id(&pack, &piece, &list));
	}
}
