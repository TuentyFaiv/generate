//! Read-only and history commands: `status`, `why`, `log`, `undo` and `detect`.

use anyhow::anyhow;
use tfverse_core::RelPath;
use tfverse_core::engine::{FileStatus, LineOrigin};

use super::Session;
use crate::context::Context;
use crate::ui::Output;

impl Session {
	pub(super) fn log(self, context: &Context) -> anyhow::Result<()> {
		let history = context.engine.history()?;
		if self.json {
			Output::json(&history);
		} else if history.is_empty() {
			println!("Nothing to undo.");
		} else {
			for transaction in history.iter().rev() {
				println!(
					"{:>4}  {}  ({} file(s))",
					transaction.id,
					transaction.summary,
					transaction.changes.len()
				);
			}
		}
		Ok(())
	}

	pub(super) fn undo(self, context: &Context, force: bool) -> anyhow::Result<()> {
		let undone = context.engine.undo(force)?;
		if self.json {
			Output::json(&undone);
		} else {
			match undone {
				Some(transaction) => println!("Undid transaction {}: {}", transaction.id, transaction.summary),
				None => println!("Nothing to undo."),
			}
		}
		Ok(())
	}

	#[allow(clippy::unused_self, reason = "every command is a session method")]
	pub(super) fn detect(self, context: &Context) -> anyhow::Result<()> {
		Output::json(&context.engine.project()?);
		Ok(())
	}

	pub(super) fn status(self, context: &Context) -> anyhow::Result<()> {
		let statuses: Vec<FileStatus> = context.engine.status()?;
		if self.json {
			Output::json(&statuses);
		} else if statuses.is_empty() {
			println!("Nothing generated yet.");
		} else {
			for status in statuses {
				println!("{:<9} {}", format!("{:?}", status.state).to_lowercase(), status.path);
			}
		}
		Ok(())
	}

	pub(super) fn why(self, context: &Context, location: &str) -> anyhow::Result<()> {
		let (path, line) = location
			.rsplit_once(':')
			.and_then(|(path, line)| Some((RelPath::new(path).ok()?, line.parse::<u32>().ok()?)))
			.ok_or_else(|| anyhow!("expected `path:line`, found `{location}`"))?;
		let provenance = context.engine.why(&path, line, &context.library)?;
		if self.json {
			Output::json(&provenance);
			return Ok(());
		}
		match provenance {
			None => println!("{path} was not generated by tfverse."),
			Some(found) => {
				let origin = match found.line {
					LineOrigin::Pack { original_line } => {
						format!("from the pack (line {original_line} of the original)")
					}
					LineOrigin::User => "yours: added or changed since generation".to_owned(),
					_ => "unknown: the original is not available".to_owned(),
				};
				println!(
					"{path}:{line} is {origin}; {} {} piece `{}`",
					found.pack, found.pack_version, found.piece
				);
			}
		}
		Ok(())
	}
}
